export function tr(text, args = []) {
  const locale = globalThis.navigator?.language?.toLowerCase() ?? '';
  const dict = locale.startsWith('zh') ? zh : locale.startsWith('pt') ? null : en;
  return (dict?.[text] ?? text).replace(/\{(\d+)\}/g, (slot, index) => args[index] ?? slot);
}
